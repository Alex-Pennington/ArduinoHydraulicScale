COMMENT ON COLUMN plc4_engine.load_pct IS
    'Engine percent load at current speed, %. SPN 92 from PGN 61443 (EEC2) byte 3, 1 %/bit, offset 0. NOT from EEC1 -- EEC1 byte 3 is percent torque, a different parameter.';
COMMENT ON COLUMN plc4_engine.torque_pct IS
