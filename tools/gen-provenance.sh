#!/usr/bin/env bash
# Generate include/build_provenance.h — the commit this binary was compiled from.
#
# Run it before any direct arduino-cli build. tools/build-check.sh and the flash
# path call it themselves; the generated header is gitignored, and a fresh clone
# falls back to the committed sentinel so it still compiles.
#
#   ./tools/gen-provenance.sh
#
# WHAT THE FIELD MEANS. BUILD_SHA is the 8-character short SHA of HEAD when this
# ran. BUILD_DIRTY is 1 when the compiled sources had uncommitted changes at that
# moment. BUILD_PROVENANCE is what the firmware publishes: the SHA alone when
# clean, SHA+"+dirty" when not.
#
# WHAT IT CANNOT TELL YOU. This identifies the commit the binary was COMPILED
# from, never the commit the repository was on when the board was FLASHED. Build
# at commit A, move the tree to B, flash the old binary, and the board truthfully
# reports A. The field answers "what source made this image", not "is the board
# up to date".
#
# WHY +dirty AND NOT A TIMESTAMP. A timestamp makes two builds of identical
# source differ, which destroys the comparison the field exists for. +dirty says
# the one thing that matters: this image contains work that is in no commit, so
# the SHA beside it does not fully describe it.
#
# WHY THE DIRTY CHECK IS SCOPED TO src AND include, AND WHY IT COUNTS UNTRACKED
# FILES. arduino-cli compiles the whole assembled sketch directory, so an
# UNTRACKED header in include/ is in the image while `git diff` — which reports
# modified tracked files only — sees nothing and this script would write
# BUILD_DIRTY 0. The header would then assert the binary is exactly <sha> when
# <sha> does not contain that code. Both halves are needed, and the query is
# scoped because a repo-wide status is non-empty on a normal working tree here
# (build artefacts, scratch files), and a check that fires on a clean tree is one
# people learn to wave through.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO/include/build_provenance.h"

cd "$REPO"

if ! git rev-parse --git-dir >/dev/null 2>&1; then
  echo "not a git repository: $REPO" >&2
  exit 1
fi

COMMIT="$(git rev-parse --short=8 HEAD)"

# Tested separately from its result: this must never read its own failure as
# "clean". An unreadable index or unparseable pathspec has to stop the script,
# not silently produce BUILD_DIRTY 0.
if ! STATUS="$(git status --porcelain -- src include)"; then
  echo "git status failed; refusing to guess at provenance" >&2
  exit 1
fi

if [ -n "$STATUS" ]; then
  DIRTY_VAL=1
  PROV_STR="${COMMIT}+dirty"
else
  DIRTY_VAL=0
  PROV_STR="${COMMIT}"
fi

cat > "$OUT" <<PROV
// build_provenance.h — AUTO-GENERATED by tools/gen-provenance.sh.
// Do not edit by hand and do not commit. Regenerate before each direct build.
#pragma once
#define BUILD_SHA        "${COMMIT}"
#define BUILD_DIRTY      ${DIRTY_VAL}
#define BUILD_PROVENANCE "${PROV_STR}"
PROV

echo "build_provenance.h written: build=${PROV_STR}"
if [ "$DIRTY_VAL" = "1" ]; then
  echo "  tree has uncommitted work under src/ or include/ -- the image is not ${COMMIT} alone:" >&2
  printf '%s\n' "$STATUS" | sed 's/^/    /' >&2
fi
